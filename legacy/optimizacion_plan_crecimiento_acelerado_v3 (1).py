def calcular_unit_economics(df, inst, resultados_dcf=None):
    """
    Calcula Unit Economics completos del plan de crecimiento.

    Incluye las métricas usadas en el anexo:
    adquisición, MoM, churn, CAC, ticket, recurrencia, ARR, GP,
    ARPU, cash burn rate, bootstrapping, LTV, LTV(2), LTV/CAC
    y clientes monetizados.
    """

    servicios = inst["servicios"]
    parametros = inst.get("parametros", inst.get("params", {}))

    beta_anual = inst["beta_anual"]
    VC = inst["VC"]

    total_adq = df["Adq_clientes"].sum()
    total_ingresos = df["Ingresos"].sum()
    total_cost_op = df["Costo_operacional"].sum()
    total_cac = df["CAC"].sum()
    total_ebitda_negativo = -df.loc[df["EBITDA"] < 0, "EBITDA"].sum()

    ticket_prom = np.mean([s["ticket"] for s in servicios])
    frecuencia_prom = np.mean([s["frecuencia"] for s in servicios])
    recurrencia_mensual = 1 / frecuencia_prom if frecuencia_prom > 0 else 0
    recurrencia_anual = 12 / frecuencia_prom if frecuencia_prom > 0 else 0

    churn_anual = np.mean([s["churn_anual"][0] for s in servicios])

    cac_prom = total_cac / total_adq if total_adq > 0 else 0

    ingresos_recurrentes = df["Ingresos_recurrentes_proxy"].sum() if "Ingresos_recurrentes_proxy" in df.columns else 0
    arr_pct = ingresos_recurrentes / total_ingresos if total_ingresos > 0 else 0

    gp = 1 - (total_cost_op / total_ingresos) if total_ingresos > 0 else 0

    # arpu = (ticket_prom * arr_pct * gp) - cac_prom
    clientes_activos_prom = df["Clientes_activos"].mean()
    arpu = (total_ingresos / (clientes_activos_prom * len(df))) if clientes_activos_prom > 0 else 0

    cbr_diario = total_ebitda_negativo / 360

    ciclo_op = parametros.get("ciclo_op", [30])[0]
    ct_base_ue = cbr_diario * ciclo_op
    bootstrapping = max(VC, ct_base_ue)

    churn_m_a1 = 1 - (1 - servicios[0]["churn_anual"][0]) ** (1/12)
    gp_marginal = 1 - servicios[0]["c_u"] / servicios[0]["ticket"]
    ltv = (ticket_prom * gp_marginal) / churn_m_a1

    van = resultados_dcf["VAN"] if resultados_dcf is not None and "VAN" in resultados_dcf else np.nan
    ltv_2 = van / total_adq if total_adq > 0 and not pd.isna(van) else np.nan

    ltv_cac = ltv / cac_prom if cac_prom > 0 else 0

    clientes_monetizados = total_adq * arr_pct

    adq_anio_1 = df[df["Año"] == 1]["Adq_clientes"].sum()
    base_adq = df[df["Año"] == 1]["Adq_clientes"].iloc[0] if len(df[df["Año"] == 1]) > 0 else np.nan
    mom_growth = ((adq_anio_1 / base_adq) ** (1 / 11) - 1) if base_adq and base_adq > 0 else np.nan

    df_units = pd.DataFrame([
        {
            "Unit Economic": "Adquisición",
            "Definición": "Clientes nuevos captados en el horizonte",
            "Fórmula / Fuente": "Σ Adquisición mensual",
            "Valor": total_adq,
            "Unidad": "# clientes",
        },
        {
            "Unit Economic": "MoM Growth",
            "Definición": "Crecimiento mensual equivalente de adquisición",
            "Fórmula / Fuente": "(Σ Adq. año 1 / base)^(1/11) - 1",
            "Valor": mom_growth,
            "Unidad": "%",
        },
        {
            "Unit Economic": "CHURN",
            "Definición": "Porcentaje de clientes perdidos en un año",
            "Fórmula / Fuente": "Parámetro promedio año 1",
            "Valor": churn_anual,
            "Unidad": "%",
        },
        {
            "Unit Economic": "CAC",
            "Definición": "Costo de adquisición por cliente",
            "Fórmula / Fuente": "Σ CAC / Σ Adquisición",
            "Valor": cac_prom,
            "Unidad": "USD/cliente",
        },
        {
            "Unit Economic": "Ticket promedio",
            "Definición": "Precio promedio por servicio",
            "Fórmula / Fuente": "Parámetro configurado",
            "Valor": ticket_prom,
            "Unidad": "USD",
        },
        {
            "Unit Economic": "Recurrencia mensual",
            "Definición": "Veces que compra cada cliente al mes",
            "Fórmula / Fuente": "1 / frecuencia promedio",
            "Valor": recurrencia_mensual,
            "Unidad": "veces/mes",
        },
        {
            "Unit Economic": "ARR",
            "Definición": "Porcentaje de ingresos recurrentes sobre total",
            "Fórmula / Fuente": "Ingresos recurrentes / Total ingresos",
            "Valor": arr_pct,
            "Unidad": "%",
        },
        {
            "Unit Economic": "Gross Profit (GP)",
            "Definición": "Margen bruto operacional",
            "Fórmula / Fuente": "1 - Costos operacionales / Ingresos",
            "Valor": gp,
            "Unidad": "%",
        },
        {
            "Unit Economic": "ARPU",
            "Definición": "Ingreso promedio por usuario",
            "Fórmula / Fuente": "Ingresos totales / clientes activos promedio * horizonte",
            "Valor": arpu,
            "Unidad": "USD/cliente",
        },
        {
            "Unit Economic": "Cash Burn Rate",
            "Definición": "Dinero consumido por día",
            "Fórmula / Fuente": "Σ EBITDA negativo / 360",
            "Valor": cbr_diario,
            "Unidad": "USD/día",
        },
        {
            "Unit Economic": "Bootstrapping",
            "Definición": "Capital de trabajo hasta punto de equilibrio",
            "Fórmula / Fuente": "max(VC, CBR × ciclo operacional)",
            "Valor": bootstrapping,
            "Unidad": "USD",
        },
        {
            "Unit Economic": "LTV",
            "Definición": "Valor total estimado que genera cada cliente",
            "Fórmula / Fuente": "(Ticket × Recurrencia anual) / β",
            "Valor": ltv,
            "Unidad": "USD/cliente",
        },
        {
            "Unit Economic": "LTV(2)",
            "Definición": "Valor por cliente medido por VAN",
            "Fórmula / Fuente": "VAN / Σ adquisición",
            "Valor": ltv_2,
            "Unidad": "USD/cliente",
        },
        {
            "Unit Economic": "LTV/CAC",
            "Definición": "Eficiencia del capital de adquisición",
            "Fórmula / Fuente": "LTV / CAC",
            "Valor": ltv_cac,
            "Unidad": "ratio",
        },
        {
            "Unit Economic": "Clientes monetizados",
            "Definición": "Clientes que compran recurrentemente",
            "Fórmula / Fuente": "Adquisición × ARR",
            "Valor": clientes_monetizados,
            "Unidad": "# clientes",
        },
    ])

    df_print = df_units.copy()

    def formatear_valor(row):
        valor = row["Valor"]
        unidad = row["Unidad"]

        if pd.isna(valor):
            return "N/D"

        if unidad == "%":
            return f"{valor * 100:,.1f}%"
        if unidad in ["USD", "USD/cliente", "USD/día"]:
            return f"USD {valor:,.0f}"
        if unidad == "ratio":
            return f"{valor:,.2f}x"
        if unidad in ["# clientes"]:
            return f"{valor:,.0f}"
        return f"{valor:,.2f}"

    df_print["Valor"] = df_print.apply(formatear_valor, axis=1)

    print("═" * 100)
    print("  UNIT ECONOMICS COMPLETOS")
    print("═" * 100)
    print(df_print.to_string(index=False))
    print("═" * 100)

    return df_units


