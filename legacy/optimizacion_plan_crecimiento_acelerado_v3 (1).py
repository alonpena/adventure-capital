def calcular_valorizacion_dcf(df, inst):
    """
    Valorización estándar mediante DCF.

    Lógica:
    - Capital de trabajo inicial = VC.
    - Flujo mensual antes de impuestos = EBITDA.
    - Impuesto solo si EBITDA > 0.
    - Flujo neto = EBITDA - impuesto.
    - Valor de desecho = EBITDA último mes anualizado * multiplicador.
    - VAN = -VC + VP(flujos mensuales) + VP(valor de desecho).

    Retorna:
    - DataFrame mensual de flujo de caja.
    - Resumen anual.
    - Métricas principales del DCF.
    """

    H = inst["H"]
    beta_mensual = inst["beta"]
    beta_anual = inst["beta_anual"]
    VC = inst["VC"]

    parametros = inst.get("parametros", inst.get("params", {}))
    tax = parametros.get("tax", 0.125)
    mult_vd_ebitda = parametros.get("mult_vd_ebitda", 1.0)

    print("═" * 80)
    print("  VALORIZACIÓN POR FLUJO DE CAJA DESCONTADO (DCF)")
    print("═" * 80)
    print(f"Capital de trabajo inicial : USD {VC:,.0f}")
    print(f"Tasa descuento anual       : {beta_anual*100:.2f}%")
    print(f"Tasa descuento mensual     : {beta_mensual*100:.3f}%")
    print(f"Tasa impuesto              : {tax*100:.1f}%")
    print(f"Multiplicador VD EBITDA    : {mult_vd_ebitda:.2f}x")
    print()

    # ================================================================
    # DataFrame mensual de flujo de caja
    # ================================================================

    fc = pd.DataFrame({
        "t": df["t"],
        "Año": df["Año"],
        "Ingresos": df["Ingresos"],
        "Costo_operacional": df["Costo_operacional"],
        "CAC": df["CAC"],
        "G_adm": df["G_adm"],
        "RRHH": df["RRHH"],
        "EBITDA": df["EBITDA"],
    })

    fc["Impuesto"] = fc["EBITDA"].apply(lambda x: max(x * tax, 0))
    fc["FC_neto"] = fc["EBITDA"] - fc["Impuesto"]
    fc["Factor_desc"] = 1 / (1 + beta_mensual) ** fc["t"]
    fc["FC_desc"] = fc["FC_neto"] * fc["Factor_desc"]

    # ================================================================
    # Valor de desecho
    # ================================================================

    ebitda_ultimo_mes = fc.iloc[-1]["EBITDA"]
    ebitda_anualizado = ebitda_ultimo_mes * 12

    valor_desecho_nominal = max(ebitda_anualizado * mult_vd_ebitda, 0)
    factor_desc_H = 1 / (1 + beta_mensual) ** H
    valor_desecho_vp = valor_desecho_nominal * factor_desc_H

    # ================================================================
    # VAN
    # ================================================================

    vp_flujos = fc["FC_desc"].sum()
    VAN = -VC + vp_flujos + valor_desecho_vp

    # ================================================================
    # Resumen anual
    # ================================================================

    resumen_anual = fc.groupby("Año").agg({
        "Ingresos": "sum",
        "Costo_operacional": "sum",
        "CAC": "sum",
        "G_adm": "sum",
        "RRHH": "sum",
        "EBITDA": "sum",
        "Impuesto": "sum",
        "FC_neto": "sum",
        "FC_desc": "sum",
    })

    print("RESUMEN ANUAL DCF")
    print("-" * 80)
    print(resumen_anual.round(0).to_string())

    print("\nRESULTADOS DCF")
    print("-" * 80)
    print(f"VP flujos operacionales   : USD {vp_flujos:,.0f}")
    print(f"EBITDA último mes         : USD {ebitda_ultimo_mes:,.0f}")
    print(f"EBITDA anualizado         : USD {ebitda_anualizado:,.0f}")
    print(f"Valor de desecho nominal  : USD {valor_desecho_nominal:,.0f}")
    print(f"Valor de desecho VP       : USD {valor_desecho_vp:,.0f}")
    print(f"Capital trabajo inicial   : USD {-VC:,.0f}")
    print("-" * 80)
    print(f"VAN                       : USD {VAN:,.0f}")
    print("═" * 80)

    return {
        "df_flujo_caja": fc,
        "resumen_anual_dcf": resumen_anual,
        "vp_flujos": vp_flujos,
        "valor_desecho_nominal": valor_desecho_nominal,
        "valor_desecho_vp": valor_desecho_vp,
        "VAN": VAN,
    }


def calcular_valorizacion_multiplos(df, inst):
    """
    Valorización básica mediante múltiplos.

    Lógica:
    - Se toma el último año del horizonte como año de referencia.
    - Se calcula valorización por múltiplo de ingresos.
    - Se calcula valorización por múltiplo de EBITDA.
    """

    parametros = inst.get("parametros", inst.get("params", {}))

    mult_ingresos = parametros.get("mult_ingresos", 1.5)
    mult_ebitda = parametros.get("mult_ebitda", 3.0)

    ultimo_anio = int(df["Año"].max())
    df_ref = df[df["Año"] == ultimo_anio].copy()

    ingresos_anual = df_ref["Ingresos"].sum()
