"""## 3. Generador de Instancia y Preprocesamiento

"""

def generar_instancia(parametros):

    """
    Construye la instancia del modelo a partir de los parámetros brutos. Retorna un diccionario de instancia.

    Preprocesa:
    - churn mensual por servicio y período
    - supervivencia acumulada por cohorte: phi[s,tau,t]
    - indicador binario de recompra: delta[s,tau,t]
    - % de recompra de cohorte tau para servicio en período t: alpha[s,tau,t]
    - adquisición base de los primeros 12 meses
    - costo de planilla de RRHH mensual
    - caja mínima mensual: B_min[t]
    - factor de descuento mensualizado: beta[t]
    """

    H = parametros["H"]

    servicios = parametros["servicios"]
    S = len(servicios)

    beta_anual = parametros["beta"]
    beta_mensual = (1 + beta_anual) ** (1 / 12) - 1

    T = list(range(1, H + 1))
    T_base = list(range(1, 13))

    # ================================================================
    # 1. Churn mensual por servicio y período
    # ================================================================
    churn_mensual = {}

    for s, servicio in enumerate(servicios):
        for t in T:
            ano = min((t - 1) // 12, len(servicio["churn_anual"]) - 1)
            churn_anual = servicio["churn_anual"][ano]

            # Conversión equivalente anual -> mensual
            churn_mensual[(s, t)] = 1 - (1 - churn_anual) ** (1 / 12)

    # ================================================================
    # 2. Supervivencia acumulada phi[s,tau,t]
    # φ_{s,τ,t} = ∏_{c=τ+1}^{t} (1 − Churn_{s,c})
    # ================================================================
    phi = {}

    for s in range(S):
        for tau in T:
            phi[(s, tau, tau)] = 1.0
            for t in range(tau + 1, H + 1):
                phi[(s, tau, t)] = phi[(s, tau, t - 1)] * (1 - churn_mensual[(s, t)])



    # ================================================================
    # 3. Indicador de recompra delta[s,tau,t]
    # δ_{s,τ,t} = 1 si t > τ y (t − τ) ≡ 0 (mod f_s)
    # ================================================================
    delta = {}

    for s, servicio in enumerate(servicios):
        frecuencia = servicio["frecuencia"]
        for tau in T:
            for t in T:
                delta[(s, tau, t)] = int(t > tau and (t - tau) % frecuencia == 0)

    # ================================================================
    # 4. Alpha por servicio y período
    # ================================================================

    alpha = {}

    for s, servicio in enumerate(servicios):
        for t in T:
            alpha[(s, t)] = servicio["alpha"]

    # ================================================================
    # 5. Adquisición base primeros 12 meses
    # ================================================================
    A_base = {}

    for s, servicio in enumerate(servicios):
        plan = servicio["A_base"]

        if len(plan) != 12:
            raise ValueError(f"A_base del servicio {s} debe tener exactamente 12 valores.")

        for t in T_base:
            A_base[(s, t)] = float(plan[t - 1])


    # ================================================================
    # 6. RRHH mensual
    # ================================================================

    RRHH = {}

    for t in T:
        ano = min((t - 1) // 12, len(parametros["RRHH_mensual"]) - 1)
        RRHH[t] = parametros["RRHH_mensual"][ano]

    # ================================================================
    # 7. Caja mínima B_min[t]
    # ================================================================

    # MVP: se calcula con burn fijo de referencia para evitar circularidad.
    # No depende de Costo óptimo del solver.
    B_min = {}

    for t in T:
        ano = min((t - 1) // 12, len(parametros["ciclo_op"]) - 1)

        ciclo_dias = parametros["ciclo_op"][ano]

        # Burn mensual de referencia: administración + RRHH + costo mínimo operacional base
        costo_min_op_ref = sum(servicio["c_min"] for servicio in servicios)
        burn_ref_mensual = parametros["g_adm"] + RRHH[t] + costo_min_op_ref

        # Capital de trabajo requerido por ciclo operacional
        # B_min[t] = (ciclo_dias / 30) * burn_ref_mensual + parametros["buffer_caja"]
        B_min[t] = 0


    # ================================================================
    # 8. Factor de descuento mensual
    # ============================================================

    descuento = {t: 1 / (1 + beta_mensual) ** t for t in T}

    instancia = {
        "H": H,
        "T": T,
        "S": S,
        "servicios": servicios,
        "beta": beta_mensual,
        "beta_anual": beta_anual,
        "descuento": descuento,
        "churn_mensual": churn_mensual,
        "phi": phi,
        "delta": delta,
        "alpha": alpha,
        "T_base": T_base,
        "A_base": A_base,
        "ciclo_op": parametros["ciclo_op"],
        "RRHH": RRHH,
        "B_min": B_min,
        "VC": parametros["VC"],
        "g_adm": parametros["g_adm"],
        "meta": parametros["meta"],
        "sup": parametros["sup"],
        "rem_v": parametros["rem_v"],
        "rem_l": parametros["rem_l"],
        "com_v": parametros["com_v"],
        "com_l": parametros["com_l"],
        "tax": parametros["tax"],
        "parametros": parametros,
        "g_max_suavizado": parametros["g_max_suavizado"],
    }

    return instancia



