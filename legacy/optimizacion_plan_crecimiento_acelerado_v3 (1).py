    # No fija el MoM; solo acota la aceleración máxima admisible.

    g = inst["g_max_suavizado"]

    for s in range(S):

        # Base de transición: mayor entre adquisición mes 12 y promedio últimos 12 meses
        promedio_base = sum(inst["A_base"][(s, t)] for t in inst["T_base"]) / len(inst["T_base"])
