def extraer_resultados(inst, vars_dict):
    """
    Extrae los resultados del modelo optimizado y construye un DataFrame mensual.

    El DataFrame conserva la lógica metodológica:
    clientes → servicios → ingresos → costos → EBITDA → caja.
    """

    H = inst["H"]
    S = inst["S"]
    T = inst["T"]
    servicios = inst["servicios"]

    def valor(variable):
        """Extrae valor numérico de una variable PuLP."""
        x = pulp.value(variable)
        return 0.0 if x is None else x

    filas = []

    for t in T:
        anio = (t - 1) // 12 + 1
        mes_anio = (t - 1) % 12 + 1

        fila = {
            "t": t,
            "Año": anio,
            "Mes": mes_anio,

            # Estructura comercial
            "Vendedores": valor(vars_dict["V"][t]),
            "Lideres": valor(vars_dict["L"][t]),

            # Resultados financieros agregados
            "CAC": valor(vars_dict["CAC"][t]),
            "EBITDA": valor(vars_dict["EBITDA"][t]),
            "Caja": valor(vars_dict["Caja"][t]),
            "RRHH": inst["RRHH"][t],
            "G_adm": inst["g_adm"],
        }

        for s in range(S):
            nombre = servicios[s]["nombre"]

            fila[f"A_{nombre}"] = valor(vars_dict["A"][(s, t)])
            fila[f"C_{nombre}"] = valor(vars_dict["C"][(s, t)])
            fila[f"R_{nombre}"] = valor(vars_dict["R"][(s, t)])
            fila[f"Q_{nombre}"] = valor(vars_dict["Q"][(s, t)])
            fila[f"I_{nombre}"] = valor(vars_dict["I"][(s, t)])
            fila[f"Cost_op_{nombre}"] = valor(vars_dict["Cost_op"][(s, t)])
            fila[f"m_op_{nombre}"] = valor(vars_dict["m_op"][(s, t)])

        filas.append(fila)

    df = pd.DataFrame(filas)

    nombres = [srv["nombre"] for srv in servicios]

    df["Adq_clientes"] = df[[f"A_{n}" for n in nombres]].sum(axis=1)
    df["Clientes_activos"] = df[[f"C_{n}" for n in nombres]].sum(axis=1)
    df["Ventas_recurrentes"] = df[[f"R_{n}" for n in nombres]].sum(axis=1)
    df["Servicios_totales"] = df[[f"Q_{n}" for n in nombres]].sum(axis=1)
    df["Ingresos"] = df[[f"I_{n}" for n in nombres]].sum(axis=1)
    df["Costo_operacional"] = df[[f"Cost_op_{n}" for n in nombres]].sum(axis=1)

    df["Costos_totales_sin_CAC"] = df["Costo_operacional"] + df["G_adm"] + df["RRHH"]
    df["Egresos_totales"] = df["Costo_operacional"] + df["CAC"] + df["G_adm"] + df["RRHH"]
    df["EBITDA_acum"] = df["EBITDA"].cumsum()

    df["MoM_adq"] = df["Adq_clientes"].pct_change().replace([np.inf, -np.inf], np.nan)
    df["MoM_ingresos"] = df["Ingresos"].pct_change().replace([np.inf, -np.inf], np.nan)

    df["Ingresos_recurrentes_proxy"] = 0.0
    for s, srv in enumerate(servicios):
        nombre = srv["nombre"]
        df["Ingresos_recurrentes_proxy"] += df[f"R_{nombre}"] * srv["ticket"]

    df["ARR_pct"] = np.where(
        df["Ingresos"] > 0,
        df["Ingresos_recurrentes_proxy"] / df["Ingresos"],
        0
    )

    return df


